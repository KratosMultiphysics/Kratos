@functools.cache
def model_part_name_of_reference(model_part_name_of_generated_mesh):
    # The interfaces have the same name in both meshes, only the wall was renamed
    if model_part_name_of_generated_mesh == generated_mesh_wall_model_part_name:
        return reference_wall_model_part_name

    return model_part_name_of_generated_mesh


def get_y_coordinates_by_node_id(
    mdpa_file_path_without_extension, wall_model_part_name
):
    model = Kratos.Model()
    main_model_part = model.CreateModelPart("PorousDomain")
    Kratos.ModelPartIO(mdpa_file_path_without_extension).ReadModelPart(main_model_part)
    return {
        node.Id: node.Y
        for node in model.GetModelPart(f"PorousDomain.{wall_model_part_name}").Nodes
    }


def get_expected_result_curves_from_csv(csv_filepath, y_coordinate_by_node_id):
    # The expected results are stored per node ID of the reference mesh.  A mesh made
    # by the geometry generator has both its own node numbering and its own node
    # positions, so the expected results are returned as curves along the wall:
    # {result item: [(y, value), ...]}, sorted by y.
    result_fieldnames = csv_fieldnames[1:]  # node ID is not a result
    curves = {fieldname: [] for fieldname in result_fieldnames}
    with open(csv_filepath, newline="") as csv_file:
        for row in csv.DictReader(csv_file):
            y_coordinate = y_coordinate_by_node_id[int(row[csv_fieldname_node])]
            for fieldname in result_fieldnames:
                curves[fieldname].append((y_coordinate, float(row[fieldname])))

    return {fieldname: sorted(points) for fieldname, points in curves.items()}


def interpolate_at(curve, y_coordinate):
    # Linear interpolation of a curve [(y, value), ...] that is sorted by y
    for (y1, value1), (y2, value2) in zip(curve, curve[1:]):
        if y1 - y_coordinate_tolerance <= y_coordinate <= y2 + y_coordinate_tolerance:
            if y2 == y1:
                return value1
            return value1 + (value2 - value1) * (y_coordinate - y1) / (y2 - y1)

    raise ValueError(
        f"Cannot interpolate at y = {y_coordinate} m: it lies outside the range "
        f"[{curve[0][0]}, {curve[-1][0]}] m covered by the expected results"
    )


def max_abs_value(curve):
    return max(abs(value) for _, value in curve)


class KratosGeoMechanicsCrowValidationGeneratedMesh(KratosUnittest.TestCase):
    def setUp(self):
        super().setUp()

        # The following attributes will be populated by the specific simulation runs
        self.test_path = None
        self.csv_files_dir = None
        self.project_parameters_file_path = None
        self.wall_model_part_name = None
        self.make_comparison_plots = False
        self.modify_project_parameters = None
        self.run_analysis = None

    def prepare_reference_test_run(
        self,
        material_model_dir_name,
        analysis_type,
        variant,
        modify_project_parameters=None,
        run_analysis=helper_utilities.run_orchestrator,
    ):
        # The case as it already exists in this repository: mesh and project parameters
        # come from the 'common' directory, the material parameters from the directory of
        # the material model.
        base_test_path = crow_validation_dir / material_model_dir_name / analysis_type
        self.test_path = base_test_path / variant
        self.test_path.mkdir(exist_ok=True)
        self.csv_files_dir = base_test_path
        self.project_parameters_file_path = (
            common_test_files_dir / f"{analysis_type}.json"
        )
        self.wall_model_part_name = reference_wall_model_part_name
        # The plots are made by the run of the generated mesh, since they compare the
        # results of both cases
        self.make_comparison_plots = False
        self.modify_project_parameters = modify_project_parameters
        self.run_analysis = run_analysis

    def prepare_generated_mesh_test_run(
        self,
        modify_project_parameters=None,
        run_analysis=helper_utilities.run_orchestrator,
    ):
        # The Python generated mesh is self-contained: the project parameters refer to the
        # mesh and the material files by their bare file names, so the analysis has to be
        # run from the directory that holds them all.
        self.test_path = generated_mesh_dir
        self.test_path.mkdir(exist_ok=True)
        # Compare against - and plot alongside - the results of the linear elastic case
        # that is already in this repository.
        self.csv_files_dir = (
            crow_validation_dir / linear_elastic_dir_name / staged_construction
        )
        self.project_parameters_file_path = (
            generated_mesh_dir / generated_mesh_project_parameters_file_name
        )
        self.wall_model_part_name = generated_mesh_wall_model_part_name
        self.make_comparison_plots = True
        self.modify_project_parameters = modify_project_parameters
        self.run_analysis = run_analysis

    def run_simulation_and_checks(self):
        with context_managers.set_cwd_to(self.test_path):
            with open(self.project_parameters_file_path, "r") as analysis_file:
                project_parameters = Kratos.Parameters(analysis_file.read())

            if self.modify_project_parameters is not None:
                self.modify_project_parameters(project_parameters)

            project = self.run_analysis(project_parameters)

        model = project.GetModel()
        sheet_pile_wall = model.GetModelPart(
            f"PorousDomain.{self.wall_model_part_name}"
        )

        if self.make_comparison_plots:
            self.create_wall_plots()
            self.create_interface_plots()
            self.create_overview_plot()

        # Check the obtained results.  Node IDs are needed to read the results of this
        # run from its own JSON output, but the comparison with the expected results is
        # made on the basis of the position along the wall, since the mesh under test
        # may have both a different node numbering and a different node distribution.
        node_ids = [node.Id for node in sheet_pile_wall.Nodes]
        y_coordinates = [node.Y for node in sheet_pile_wall.Nodes]

        y_coordinate_by_reference_node_id = get_y_coordinates_by_node_id(
            common_test_files_dir / reference_mesh_file_name_without_extension,
            reference_wall_model_part_name,
        )
        reference_y_coordinates = y_coordinate_by_reference_node_id.values()
        self.assertGreaterEqual(
            min(y_coordinates),
            min(reference_y_coordinates) - y_coordinate_tolerance,
            msg="The wall reaches deeper than the wall of the expected results",
        )
        self.assertLessEqual(
            max(y_coordinates),
            max(reference_y_coordinates) + y_coordinate_tolerance,
            msg="The wall reaches higher than the wall of the expected results",
        )

        for stage_name in stages_to_be_checked:
            json_output = json_utilities.read_external_json(
                self.file_path_to_json_output(stage_name, wall_output_postfix)
            )

            csv_filepath = (
                self.csv_files_dir / f"{stage_name}__expected_results_wall.csv"
            )
            expected_curves = get_expected_result_curves_from_csv(
                csv_filepath, y_coordinate_by_reference_node_id
            )

            expected_max_abs_bending_moment = max_abs_value(
                expected_curves[csv_fieldname_bending_moment]
            )
            expected_max_abs_shear_force = max_abs_value(
                expected_curves[csv_fieldname_shear_force]
            )
            expected_max_abs_horizontal_total_displacement = max_abs_value(
                expected_curves[csv_fieldname_horizontal_total_displacement]
            )

            relative_tolerance = 0.02

            for (
                node_id,
                y_coordinate,
                bending_moment,
                shear_force,
                horizontal_total_displacement,
            ) in zip(
                node_ids,
                y_coordinates,
                test_helper.get_bending_moments_from_json_output(json_output, node_ids),
                test_helper.get_shear_forces_from_json_output(json_output, node_ids),
                test_helper.get_total_displacement_x_from_json_output(
                    json_output, node_ids
                ),
            ):
                expected_bending_moment = interpolate_at(
                    expected_curves[csv_fieldname_bending_moment], y_coordinate
                )
                self.assertAlmostEqual(
                    bending_moment,
                    expected_bending_moment,
                    places=None,
                    delta=test_helper.calculate_delta(
                        expected_bending_moment,
                        absolute_tolerance=relative_tolerance
                        * expected_max_abs_bending_moment,
                        relative_tolerance=relative_tolerance,
                    ),
                    msg=f"Bending moment at node {node_id} (y = {y_coordinate} m) in stage '{stage_name}'",
                )

                expected_shear_force = interpolate_at(
                    expected_curves[csv_fieldname_shear_force], y_coordinate
                )
                self.assertAlmostEqual(
                    shear_force,
                    expected_shear_force,
                    places=None,
                    delta=test_helper.calculate_delta(
                        expected_shear_force,
                        absolute_tolerance=relative_tolerance
                        * expected_max_abs_shear_force,
                        relative_tolerance=relative_tolerance,
                    ),
                    msg=f"Shear force at node {node_id} (y = {y_coordinate} m) in stage '{stage_name}'",
                )

                expected_horizontal_total_displacement = interpolate_at(
                    expected_curves[csv_fieldname_horizontal_total_displacement],
                    y_coordinate,
                )
                self.assertAlmostEqual(
                    horizontal_total_displacement,
                    expected_horizontal_total_displacement,
                    places=None,
                    delta=test_helper.calculate_delta(
                        expected_horizontal_total_displacement,
                        absolute_tolerance=relative_tolerance
                        * expected_max_abs_horizontal_total_displacement,
                        relative_tolerance=relative_tolerance,
                    ),
                    msg=f"Horizontal total displacement at node {node_id} (y = {y_coordinate} m) in stage '{stage_name}'",
                )

    def file_path_to_json_output(self, stage_name, postfix):
        return self.test_path / f"{stage_name}__{postfix}.json"

    def get_cases_to_be_plotted(self, model_part_name_of_generated_mesh):
        # Each case is a (label, directory holding the JSON output, {node ID: y}, line
        # style, marker) tuple.  The results of the generated mesh are compared with the
        # results of the case that is already in this repository, and with nothing else.
        return [
            (
                generated_mesh_plot_label,
                self.test_path,
                get_y_coordinates_by_node_id(
                    generated_mesh_dir / generated_mesh_file_name_without_extension,
                    model_part_name_of_generated_mesh,
                ),
                "-",
                ".",
            ),
            (
                reference_plot_label,
                crow_validation_dir
                / linear_elastic_dir_name
                / staged_construction
                / reference_variant_dir_name,
                get_y_coordinates_by_node_id(
                    common_test_files_dir / reference_mesh_file_name_without_extension,
                    model_part_name_of_reference(model_part_name_of_generated_mesh),
                ),
                "--",
                "x",
            ),
        ]

    def get_variable_collections_per_stage(
        self,
        kratos_variable_label,
        stage_names,
        cases,
        postfix_json_output,
        transform_output,
    ):
        variable_data_collections = []
        for stage_name in stage_names:
            data_series_collection = []
            for (
                label,
                results_dir,
                y_coordinate_by_node_id,
                line_style,
                marker,
            ) in cases:
                json_file_path = (
                    results_dir / f"{stage_name}__{postfix_json_output}.json"
                )
                if not json_file_path.exists():
                    raise FileNotFoundError(
                        f"{json_file_path} does not exist. Run the whole test script, so "
                        f"that the case that is already in this repository is run too."
                    )

                json_data = json_utilities.read_external_json(json_file_path)
                node_ids = list(y_coordinate_by_node_id.keys())
                values = [
                    transform_output(value)
                    for value in test_helper.get_nodal_values_from_json_output(
                        json_data, kratos_variable_label, node_ids
                    )
                ]

                sorted_y, sorted_values = zip(
                    *sorted(zip(y_coordinate_by_node_id.values(), values))
                )
                data_series_collection.append(
                    plot_utils.DataSeries(
                        list(zip(sorted_values, sorted_y)),
                        label,
                        line_style=line_style,
                        marker=marker,
                    )
                )

            variable_data_collections.append(data_series_collection)

        return variable_data_collections

    def get_model_part_name_for(self, definition):
        return (
            self.wall_model_part_name if definition.on_the_wall else interface_model_part_name
        )

    def get_data_series_collections_for(self, definition):
        return self.get_variable_collections_per_stage(
            definition.kratos_variable_label,
            stages_to_be_plotted,
            self.get_cases_to_be_plotted(self.get_model_part_name_for(definition)),
            definition.postfix_json_output,
            definition.transform_output,
        )

    def create_plots_for(self, definitions):
        for definition in definitions:
            plot_utils.make_sub_plots(
                self.get_data_series_collections_for(definition),
                self.test_path / definition.plot_file_name,
                titles=stages_to_be_plotted,
                xlabel=definition.xlabel,
                ylabel=r"$y$ [m]",
            )

    def create_wall_plots(self):
        self.create_plots_for(wall_plot_definitions)

    def create_interface_plots(self):
        self.create_plots_for(interface_plot_definitions)

    def create_overview_plot(self):
        # All results on a single page, for presentation purposes: one row per result
        # item, one column per stage
        definitions = wall_plot_definitions + interface_plot_definitions

        data_series_collections = []
        subplot_options = []
        for definition in definitions:
            data_series_collections.extend(
                self.get_data_series_collections_for(definition)
            )
            subplot_options.extend(
                plot_utils.SubPlotOptions(
                    title=stage_name, xlabel=definition.xlabel, ylabel=r"$y$ [m]"
                )
                for stage_name in stages_to_be_plotted
            )

        panel_width, panel_height = overview_panel_size_in_inches
        figsize = (
            panel_width * len(stages_to_be_plotted),
            panel_height * len(definitions),
        )
        with plt.rc_context(overview_rc_params):
            for plot_file_name in overview_plot_file_names:
                plot_utils.make_separate_sub_plots(
                    data_series_collections,
                    self.test_path / plot_file_name,
                    subplot_options,
                    max_plots_per_row=len(stages_to_be_plotted),
                    figsize=figsize,
                )

    def update_all_expected_results(self):
        print("Updating the expected results...")

        self.update_expected_results(linear_elastic_dir_name, "as-is")

    def update_expected_results(self, case_name, variant):
        base_test_path = crow_validation_dir / case_name / staged_construction
        self.test_path = base_test_path / variant
        self.csv_files_dir = base_test_path

        mdpa_file_path_without_file_extension = common_test_files_dir / "model"
        model = Kratos.Model()
        main_model_part = model.CreateModelPart("PorousDomain")
        Kratos.ModelPartIO(mdpa_file_path_without_file_extension).ReadModelPart(
            main_model_part
        )
        node_ids = [
            node.Id
            for node in model.GetModelPart(
                f"PorousDomain.{reference_wall_model_part_name}"
            ).Nodes
        ]

        for stage_name in stages_to_be_checked:
            json_output = json_utilities.read_external_json(
                self.file_path_to_json_output(stage_name, wall_output_postfix)
            )

            with open(
                self.csv_files_dir / f"{stage_name}__expected_results_wall.csv",
                "w",
                newline="",
            ) as csv_file:
                writer = csv.DictWriter(csv_file, fieldnames=csv_fieldnames)

                writer.writeheader()
                for (
                    node_id,
                    bending_moment,
                    shear_force,
                    normal_force,
                    horizontal_total_displacement,
                ) in zip(
                    node_ids,
                    test_helper.get_bending_moments_from_json_output(
                        json_output, node_ids
                    ),
                    test_helper.get_shear_forces_from_json_output(
                        json_output, node_ids
                    ),
                    test_helper.get_normal_forces_from_json_output(
                        json_output, node_ids
                    ),
                    test_helper.get_total_displacement_x_from_json_output(
                        json_output, node_ids
                    ),
                ):
                    writer.writerow(
                        {
                            csv_fieldname_node: node_id,
                            csv_fieldname_bending_moment: f"{bending_moment:.6}",
                            csv_fieldname_shear_force: f"{shear_force:.6}",
                            csv_fieldname_normal_force: f"{normal_force:.6}",
                            csv_fieldname_horizontal_total_displacement: f"{horizontal_total_displacement:.6}",
                        }
                    )

    def test_staged_construction_with_linear_elastic_behavior(self):
        self.prepare_reference_test_run(
            material_model_dir_name=linear_elastic_dir_name,
            analysis_type=staged_construction,
            variant="as-is",
        )
        self.run_simulation_and_checks()

    def test_staged_construction_with_linear_elastic_behavior_on_generated_mesh(self):
        self.prepare_generated_mesh_test_run()
        self.run_simulation_and_checks()


